"""Order and fill records."""

from __future__ import annotations

from dataclasses import dataclass

import pandas as pd

from .ids import SecurityId

# Order kinds
ORDER = "order"              # ctx.order
TARGET = "target_weights"    # ctx.target_weights
CLOSE = "close"              # ctx.close
EXIT_AFTER = "exit_after"    # scheduled exit
STOP = "stop"                # stop hit (also the exit reason)
TARGET_HIT = "target"        # profit target hit (exit reason; order kind is "target_hit")
STOPPED_TRADING = "stopped_trading"

# Statuses
PENDING = "pending"
FILLED = "filled"
RESIZED = "resized"
REJECTED = "rejected"
SKIPPED = "skipped"          # no price data
NO_CHANGE = "no_change"
CANCELLED = "cancelled"


@dataclass
class Order:
    """An order queued by a strategy or generated by the engine."""

    order_id: int
    created: pd.Timestamp
    fill_idx: int
    security_id: SecurityId
    ticker: str
    at: str
    kind: str
    source: str
    shares: float | None = None
    pct: float | None = None
    value: float | None = None
    weight: float | None = None
    stop: float | None = None
    target: float | None = None
    exit_after: int | None = None
    tag: str | None = None
    lot_id: int | None = None
    signal_id: int | None = None
    exit_reason: str | None = None
    # outcome
    status: str = PENDING
    requested_qty: float | None = None
    filled_qty: float = 0.0
    fill_date: pd.Timestamp | None = None
    fill_price: float | None = None
    commission: float = 0.0
    message: str = ""

    @property
    def has_exit_rules(self) -> bool:
        return self.stop is not None or self.target is not None or self.exit_after is not None

    def record(self) -> dict:
        return {
            "order_id": self.order_id,
            "created": self.created,
            "security_id": str(self.security_id),
            "ticker": self.ticker,
            "kind": self.kind,
            "source": self.source,
            "at": self.at,
            "shares": self.shares,
            "pct": self.pct,
            "value": self.value,
            "weight": self.weight,
            "stop": self.stop,
            "target": self.target,
            "exit_after": self.exit_after,
            "tag": self.tag,
            "lot_id": self.lot_id,
            "status": self.status,
            "requested_qty": self.requested_qty,
            "filled_qty": self.filled_qty,
            "fill_date": self.fill_date,
            "fill_price": self.fill_price,
            "commission": self.commission,
            "message": self.message,
        }


@dataclass(frozen=True)
class Fill:
    """A completed fill, passed to ``on_fill``.

    Attributes:
        date: Session the fill happened on.
        ticker: Ticker filled.
        qty: Signed shares: positive bought, negative sold.
        price: Fill price per share, after slippage (adjusted-price terms).
        commission: Commission paid on this fill.
        order_id: Id returned when the order was placed.
        at: ``"open"``, ``"close"`` or ``"intraday"`` (stop/target fills).
        reason: ``"entry"`` for buys; for sells the exit reason
            (``"sell"``, ``"rebalance"``, ``"close"``, ``"exit_after"``,
            ``"stop"``, ``"target"``, ``"stopped_trading"``).
        tag: Tag given when the order was placed, if any.
    """

    date: pd.Timestamp
    ticker: str
    qty: float
    price: float
    commission: float
    order_id: int
    at: str
    reason: str
    tag: str | None
